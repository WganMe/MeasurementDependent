#!/usr/bin/env python3
"""Check that the supplement's title matches the manuscript's, and its tables are labelled.

WHY THIS EXISTS. The supplement is generated by make_supplement.py as a separate
document with its own \\Title. Nothing in the build compares that title with the
manuscript's, so the two can drift apart. They did: the supplement's source header
and its working title still named the paper "Reported Clustering Trends in a Growing
Urban Sensor Network Depend on the Measurement Protocol" after main.tex had been
retitled to \"Measurement-Dependent Clustering in the Growing Urban Observatory
Sensor Network\". The stale string then shipped inside submission_bundle.zip.

A reader who downloads a supplement whose own title names a paper that no longer
exists has no way to tell which document is current, so the check is a gate and not
a warning.

WHAT IT CHECKS
  1. The supplement's \\Title contains the manuscript's \\Title, so the two agree.
  2. No superseded title is present anywhere in the generated supplement. The list
     below is not guessed: a string is added to it when it has actually been retired.
  3. Tables are renumbered with an S prefix, which is how PeerJ wants supplementary
     elements labelled (Table S1, Figure S1). A supplement that numbers its tables
     1..N collides with the manuscript's own numbering.
  4. The supplement cites nothing that the main text does not, since PeerJ allows
     references in supplementary files only if they also appear in the main list.

Usage:
    python3 check_supplement.py            # report
    python3 check_supplement.py --quiet    # exit code only

Exit status: 0 if the supplement is consistent with the manuscript, 1 otherwise.
"""
from __future__ import annotations

import argparse
import pathlib
import re
import sys

HERE = pathlib.Path(__file__).resolve().parent
MAIN = HERE / "main.tex"
SI = HERE / "main_si.tex"

# Titles this paper has carried and no longer does. Each entry was a real title that
# shipped in a generated file, not a hypothetical one. Add to this list when a title
# is retired; do not remove entries, because an old bundle may still be in circulation.
RETIRED_TITLES = [
    "Reported Clustering Trends in a Growing Urban Sensor Network",
]

TOKEN = re.compile(r"[A-Za-z][A-Za-z'-]+")


def title_of(text: str) -> str:
    """Return the argument of \\Title{...}, flattened and without markup."""
    m = re.search(r"\\Title\{(.*?)\}\s*(?:\n|\\\\|$)", text, re.DOTALL)
    if not m:
        return ""
    t = re.sub(r"\\\\", " ", m.group(1))
    t = re.sub(r"\\[A-Za-z]+", " ", t)
    return re.sub(r"\s+", " ", t).strip(" {}")


def significant_words(title: str) -> list[str]:
    """Content words of a title, dropping very short ones and the words that any
    title in this project shares, so the comparison tests the distinctive part."""
    stop = {"the", "a", "an", "in", "of", "and", "on", "for", "to", "with", "by"}
    return [w.lower() for w in TOKEN.findall(title)
            if w.lower() not in stop and len(w) > 2]


def check() -> list[str]:
    problems: list[str] = []
    if not MAIN.is_file() or not SI.is_file():
        return ["main.tex or main_si.tex is missing"]

    main_text, si_text = MAIN.read_text(), SI.read_text()
    main_title, si_title = title_of(main_text), title_of(si_text)
    if not main_title:
        problems.append("main.tex has no \\Title")
    if not si_title:
        problems.append("main_si.tex has no \\Title")

    # 1. The supplement must name the manuscript it belongs to.
    if main_title and si_title:
        missing = [w for w in significant_words(main_title)
                   if w not in si_title.lower()]
        if missing:
            problems.append(
                "the supplement's title does not match the manuscript's. Word(s) "
                "in main.tex but not in main_si.tex: %s\n"
                "      main.tex : %s\n      main_si  : %s"
                % (", ".join(missing), main_title, si_title))

    # 2. No retired title anywhere in the generated supplement.
    for old in RETIRED_TITLES:
        if old.lower() in si_text.lower():
            line = next((i for i, l in enumerate(si_text.splitlines(), 1)
                         if old.lower() in l.lower()), 0)
            problems.append(
                "main_si.tex:%d still carries a superseded title: %r. A reader "
                "cannot tell which document is current." % (line, old))

    # 3. Supplementary elements are labelled with an S prefix.
    if "\\begin{table}" in si_text and "\\thetable}{S" not in si_text.replace(" ", ""):
        problems.append(
            "the supplement has tables but does not prefix their numbers with S, so "
            "they collide with the manuscript's own Table 1..N. Add "
            "\\renewcommand{\\thetable}{S\\arabic{table}}.")
    if "\\begin{figure}" in si_text and "\\thefigure}{S" not in si_text.replace(" ", ""):
        problems.append(
            "the supplement has figures but does not prefix their numbers with S. Add "
            "\\renewcommand{\\thefigure}{S\\arabic{figure}}.")

    # 4. A supplement may cite only what the main text already cites.
    si_cites: set[str] = set()
    for m in re.finditer(r"\\cite\{([^}]*)\}", si_text):
        si_cites |= {k.strip() for k in m.group(1).split(",") if k.strip()}
    main_cites = set(re.findall(r"\\cite\{([^}]*)\}", main_text))
    main_keys: set[str] = set()
    for c in main_cites:
        main_keys |= {k.strip() for k in c.split(",") if k.strip()}
    orphans = sorted(si_cites - main_keys)
    if orphans:
        problems.append(
            "the supplement cites keys that are not cited in the main text (%s). "
            "PeerJ permits supplementary citations only if they also appear in the "
            "main list." % ", ".join(orphans))

    return problems


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--quiet", action="store_true", help="exit code only")
    a = ap.parse_args(argv)

    problems = check()
    if not a.quiet:
        mt, st = title_of(MAIN.read_text()), title_of(SI.read_text())
        print("supplement consistency")
        print("  manuscript title : %s" % (mt or "(none)"))
        print("  supplement title : %s" % (st or "(none)"))
        print("  checked: the titles agree, no retired title remains, supplementary")
        print("           tables carry the S prefix, and no orphan citations")
        print()
    if problems:
        if not a.quiet:
            print("BLOCKING:")
            for p in problems:
                print("  - %s" % p)
        return 1
    if not a.quiet:
        print("OK: the supplement is consistent with the manuscript.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
